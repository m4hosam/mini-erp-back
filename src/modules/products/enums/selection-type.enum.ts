/**
 * Selection type for modifier groups.
 *
 * - SINGLE: Customer can select only one modifier from the group (e.g., size: Small/Medium/Large)
 * - MULTIPLE: Customer can select multiple modifiers from the group (e.g., toppings: cheese, tomatoes, lettuce)
 */
export enum SelectionType {
  SINGLE = 'SINGLE',
  MULTIPLE = 'MULTIPLE',
}
